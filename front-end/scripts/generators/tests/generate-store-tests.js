function generateMockActionCall(action, storeName) {
  const calls = {
    login: `result.current.login({ id: 1, name: 'Test' }, 'token')`,
    logout: `result.current.logout()`,
    addItem: `result.current.addItem({ id: 1, name: 'Test', price: 100, quantity: 1 })`,
    removeItem: `result.current.removeItem(1)`,
    clearCart: `result.current.clearCart()`,
    showNotification: `result.current.showNotification({ id: '1', type: 'info', message: 'Test' })`,
    setTheme: `result.current.setTheme('dark')`,
  };

  return calls[action] || `result.current.${action}()`;
}

// ====================================================================
// MAIN EXECUTION
// ====================================================================

function main() {
  console.log('🚀 Zustand Store Test Generator\n');

  if (options.dryRun) {
    console.log('🔍 DRY RUN MODE - No files will be written\n');
  }

  let generated = 0;
  let skipped = 0;

  for (const store of STORES) {
    const testFilePath = path.join(STORE_DIR, '__tests__', `${store.name}.test.ts`);
    const testContent = generateStoreTest(store);

    // Check if test already exists
    if (fs.existsSync(testFilePath) && !options.overwrite) {
      console.log(`⏭️  Skipping ${store.name} (already exists)`);
      skipped++;
      continue;
    }

    if (options.dryRun) {
      console.log(`✅ Would generate: ${testFilePath}`);
      if (options.verbose) {
        console.log('─'.repeat(70));
        console.log(testContent.substring(0, 500) + '...\n');
      }
      generated++;
    } else {
      // Ensure __tests__ directory exists
      const testDir = path.dirname(testFilePath);
      if (!fs.existsSync(testDir)) {
        fs.mkdirSync(testDir, { recursive: true });
      }

      // Write test file
      fs.writeFileSync(testFilePath, testContent, 'utf-8');
      console.log(`✅ Generated: ${testFilePath}`);
      generated++;
    }
  }

  console.log('\n' + '═'.repeat(70));
  console.log(`📊 Summary:`);
  console.log(`   Generated: ${generated}`);
  console.log(`   Skipped:   ${skipped}`);
  console.log(`   Total:     ${STORES.length}`);
  console.log('═'.repeat(70));

  if (options.dryRun) {
    console.log('\n💡 Run without --dry-run to write files');
  } else {
    console.log('\n✨ Done! Run tests with: npm run test');
  }
}

main();

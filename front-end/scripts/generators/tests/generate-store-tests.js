/**
 * ====================================================================
 * ZUSTAND STORE TEST GENERATOR
 * ====================================================================
 *
 * Génère des tests complets pour les stores Zustand avec:
 * - Tests unitaires de toutes les actions
 * - Tests de persistence (localStorage)
 * - Tests d'intégration
 * - Tests de selectors
 * - Mock de dépendances externes
 *
 * Usage:
 *   node generate-store-tests.js
 *   node generate-store-tests.js --dry-run
 *   node generate-store-tests.js --overwrite
 */

